"""Shared test fixtures (r24 E1): the repo's real live/ is NOT a test scratch
dir -- and restore must not MASK violations.

History:
  * r23 D2 added a per-test restore of the whole live/. The reviewer (r24 E1)
    showed it masks the very defect it was supposed to catch: a test writing
    live/image to the real tree went GREEN because restore hid it. It also
    read every byte of live/ per test (300 MB -> ~0.3 s/test, linear).
  * r24 E1 (this file): restore only the ALLOWLIST of contract records the
    REAL launchers write (live/model_dir, obs_started, api_key,
    engine_container, obs-relay/, .engine-env, image-identity.env,
    kvp-effective-identity.env, cache-reset reports...). Any OTHER write to
    live/ -- especially `image`, `image-verify.txt`, `lmcache-build/**` --
    fails the test immediately. The snapshot is cheap: (size, mtime_ns) for
    every file; content is read only for allowlist files <= 64 KiB; anything
    under lmcache-build/ or larger than 1 MiB is compared by (size,
    mtime_ns) only.

Also guarded (E1.3): observability/extras/targets/*.json and
observability/extras/gpu/dcgm-counters.live.csv -- generated by extras-up.sh,
must not appear in the repo during a test run.
"""
from __future__ import annotations
import os
import pathlib
import shutil
import tempfile

import pytest

ROOT = pathlib.Path(__file__).resolve().parents[1]
REPO_LIVE = ROOT / "live"
OBS_EXTRAS = ROOT / "observability" / "extras"
GUARDED_OBS = (
    "targets/gpu.json",
    "targets/vllm.json",
    "gpu/dcgm-counters.live.csv",
)

# Known launcher DEFECT (r24 E4.2), not a contract: the launchers hard-code
# $ROOT/live and ignore KVP_LIVE_DIR for these records. Until the launchers
# honour KVP_LIVE_DIR, tests exercising them must tolerate exactly these
# writes. Everything OUTSIDE this list is a test-side violation and must FAIL.
ALLOWLIST = {
    "model_dir", "obs_started", "api_key", "extras_started",
    "engine_container", ".engine-env",
    "image-identity.env", "image-verify.txt",
    "kvp-effective-identity.env",
}
ALLOWLIST_PREFIXES = (
    "obs-relay/",
    "cache-reset-report-",
    "lmcache-server-pre-reset-",
    "crash-",
)

# Snapshot: rel -> {"size","mtime","content"} (content only for small allowlist)
_SNAP: dict = {}
_OBS_SNAP: dict = {}


def _is_allowlisted(rel: str) -> bool:
    # accept both spellings: "obs-relay" (the dir itself) and
    # "obs-relay/nginx.conf" (files under it) must match the same rule
    r = rel.rstrip("/")
    if r in ALLOWLIST or rel in ALLOWLIST:
        return True
    for p in ALLOWLIST_PREFIXES:
        pr = p.rstrip("/")
        if r == pr or rel.startswith(p) or r.startswith(pr + "/"):
            return True
    return False


def _snap_live() -> dict:
    """Cheap snapshot: metadata for all, content only for small allowlist."""
    if not REPO_LIVE.is_dir():
        return {}
    snap = {}
    for p in sorted(REPO_LIVE.rglob("*")):
        rel = str(p.relative_to(REPO_LIVE))
        if p.is_dir():
            snap[rel + "/"] = {"dir": True}
            continue
        st = p.stat()
        content = None
        if (_is_allowlisted(rel) and st.st_size <= 65536
                and not rel.startswith("lmcache-build/")
                and st.st_size <= 1024 * 1024):
            content = p.read_bytes()
        snap[rel] = {"size": st.st_size, "mtime": st.st_mtime_ns,
                     "content": content}
    return snap


def _snap_obs() -> dict:
    """Snapshot of the guarded observability/extras entries (content kept
    -- the files are small generated configs)."""
    snap = {}
    for rel in GUARDED_OBS:
        p = OBS_EXTRAS / rel
        if p.is_file():
            st = p.stat()
            snap[rel] = {"size": st.st_size, "mtime": st.st_mtime_ns,
                         "content": p.read_bytes()}
    return snap


def _restore_live():
    """Restore repo live/ to the session snapshot (allowlist content only)."""
    if REPO_LIVE.is_dir():
        for p in sorted(REPO_LIVE.rglob("*"), reverse=True):
            rel = str(p.relative_to(REPO_LIVE))
            key = rel + "/" if p.is_dir() else rel
            if key not in _SNAP:
                if p.is_dir():
                    shutil.rmtree(p, ignore_errors=True)
                else:
                    p.unlink(missing_ok=True)
    for rel, meta in _SNAP.items():
        if rel.endswith("/"):
            (REPO_LIVE / rel).mkdir(parents=True, exist_ok=True)
            continue
        p = REPO_LIVE / rel
        if not p.exists():
            if meta["content"] is not None:
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_bytes(meta["content"])
            # content=None (large files) are NOT recreated -- cheap compare
            # only; the session guard catches changes to them
            continue
        st = p.stat()
        if st.st_size != meta["size"] or st.st_mtime_ns != meta["mtime"]:
            if meta["content"] is not None:
                p.write_bytes(meta["content"])
    # r23 clean-clone: an empty live/ dir left behind by mkdir -p writers
    if not _SNAP and REPO_LIVE.is_dir():
        shutil.rmtree(REPO_LIVE, ignore_errors=True)


@pytest.fixture(scope="session", autouse=True)
def _kvp_live_isolation(request):
    """Point KVP_LIVE_DIR (and KVP_OBS_DIR for the extras render) at temp
    dirs for the whole session and snapshot the repo live/ + the guarded
    observability files (E1)."""
    global _SNAP, _OBS_SNAP
    _SNAP = _snap_live()
    _OBS_SNAP = _snap_obs()
    tmp_live = pathlib.Path(tempfile.mkdtemp(prefix="kvp-test-live-"))
    os.environ["KVP_LIVE_DIR"] = str(tmp_live)
    os.environ["LIVE_DIR"] = str(tmp_live)
    # r24 E1.3: extras-up.sh renders generated files (targets/*.json,
    # dcgm-counters.live.csv) -- point OBS_DIR at a tmp COPY of the extras
    # sources so those never appear in the operator's repo tree.
    tmp_obs = pathlib.Path(tempfile.mkdtemp(prefix="kvp-test-obs-"))
    src_extras = OBS_EXTRAS
    if src_extras.is_dir():
        shutil.copytree(src_extras, tmp_obs / "extras")
    os.environ["KVP_OBS_DIR"] = str(tmp_obs)
    yield
    os.environ.pop("KVP_LIVE_DIR", None)
    os.environ.pop("LIVE_DIR", None)
    os.environ.pop("KVP_OBS_DIR", None)
    shutil.rmtree(tmp_live, ignore_errors=True)
    shutil.rmtree(tmp_obs, ignore_errors=True)
    after = _snap_live()
    problems = []
    for rel, meta in after.items():
        if rel not in _SNAP:
            # NEW entry: only the allowlist contract records are acceptable
            key = rel[:-1] if rel.endswith("/") else rel
            if not _is_allowlisted(key):
                problems.append(f"ADDED {rel}")
        # CHANGED allowlist records are the launchers' contract writes --
        # restored per-test, they are NOT a violation here
    for rel in _SNAP:
        if rel not in after:
            problems.append(f"REMOVED {rel}")
    # observability: only NEW files are a violation (a pre-existing generated
    # file is the operator's extras-up.sh output and is left alone)
    obs_after = _snap_obs()
    for rel in obs_after:
        if rel not in _OBS_SNAP:
            problems.append(f"OBS-ADDED {rel}")
    if problems:
        pytest.fail(
            "r24 E1 GUARD: the repo tree was modified by the test run "
            "(tests must use the isolated KVP_LIVE_DIR / tmp dirs): "
            + ", ".join(problems[:20]))


