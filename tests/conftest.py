"""Shared test fixtures (r25 G5/G6): the repo's real live/ is NOT a test
scratch dir -- and restore must not MASK violations (r24 E1) and must not
CASCADE one violation into every later test (r25 G5).

r24 E1: restore only the ALLOWLIST of launcher-record writes; any other
write to live/ (image, image-verify.txt, lmcache-build/**) or to the guarded
observability/extras generated files FAILS the test immediately.
r25 G5: the content of every non-allowlist file <= 64 KiB is snapshotted and
RESTORED after the violation is recorded (one red test, the next green, the
tree back to its original bytes). For large files only (size, mtime_ns) is
compared; on a size change the violation is recorded once and the NEW state
becomes the baseline -- no cascade; mtime is restored via os.utime.
r25 G6: the per-test walk touches only the top level of live/ + obs-relay/ +
crash-*; lmcache-build/ is checked by top-level entries (names + size +
mtime) only; the full walk runs once per session (before/after).

Also guarded (E1.3): observability/extras/targets/*.json and
observability/extras/gpu/dcgm-counters.live.csv -- generated by extras-up.sh,
must not appear in the repo during a test run.
"""
from __future__ import annotations
import os
import pathlib
import shutil
import sys
import tempfile

import pytest

ROOT = pathlib.Path(__file__).resolve().parents[1]
REPO_LIVE = ROOT / "live"
OBS_EXTRAS = ROOT / "observability" / "extras"
GUARDED_OBS = (
    "targets/gpu.json",
    "targets/vllm.json",
    "gpu/dcgm-counters.live.csv",
)

# Known launcher DEFECT (r24 E4.2), not a contract: the launchers hard-code
# $ROOT/live and ignore KVP_LIVE_DIR for these records. Until the launchers
# honour KVP_LIVE_DIR, tests exercising them must tolerate exactly these
# writes. Everything OUTSIDE this list is a test-side violation and must FAIL.
ALLOWLIST = {
    "model_dir", "obs_started", "api_key", "extras_started",
    "engine_container", ".engine-env",
    "image-identity.env", "image-verify.txt",
    "kvp-effective-identity.env",
}
ALLOWLIST_PREFIXES = (
    "obs-relay",
    "cache-reset-report-",
    "lmcache-server-pre-reset-",
    "crash-",
)
# r25 G6: directories whose FILE CONTENT is walked per-test (cheap); the big
# generated dir lmcache-build/ is checked by top-level entries only.
WALK_PREFIXES = ("obs-relay", "crash-")
LARGE = 65536  # content snapshot limit for non-allowlist files (r25 G5)

_SNAP: dict = {}        # session baseline (top-level): rel -> meta dict
_SNAP_DEEP: dict = {}   # deep entries under lmcache-build/** (session-end only)
_OBS_SNAP: dict = {}
# r25 G5: files that a test ADDED and the guard re-based (accepted as the
# new baseline after one violation) -- they were not part of the original
# tree, so the session guard must not report their later removal as REMOVED.
_REBASED: set = set()
_SNAP_ORIG: dict = {}   # immutable copy of the session-start snapshot


def _is_allowlisted(rel: str) -> bool:
    r = rel.rstrip("/")
    if r in ALLOWLIST or rel in ALLOWLIST:
        return True
    for p in ALLOWLIST_PREFIXES:
        pr = p.rstrip("/")
        if r == pr or rel.startswith(p) or r.startswith(pr + "/"):
            return True
    return False


def _entry(p: pathlib.Path, rel: str) -> dict:
    """One snapshot entry: dirs -> {'dir': True}; files -> size/mtime +
    content when <= 64 KiB and NOT under lmcache-build/ (r25 G5)."""
    if p.is_dir():
        return {"dir": True}
    st = p.stat()
    content = None
    if st.st_size <= LARGE and not rel.startswith("lmcache-build/"):
        content = p.read_bytes()
    return {"size": st.st_size, "mtime": st.st_mtime_ns, "content": content}


def _snap_live() -> tuple:
    """Session snapshot (full walk -- once per session). Returns
    (top-level dict, deep dict): deep entries (inside lmcache-build/**) are
    only checked ONCE per session (the full walk at the end) -- iterating
    thousands of them per test is the O(n) cost G6 forbids."""
    if not REPO_LIVE.is_dir():
        return {}, {}
    top: dict = {}
    deep: dict = {}
    for p in sorted(REPO_LIVE.rglob("*")):
        rel = str(p.relative_to(REPO_LIVE))
        key = rel + "/" if p.is_dir() else rel
        entry = _entry(p, rel)
        if rel.startswith("lmcache-build/") and "/" in rel[len("lmcache-build/"):]:
            deep[key] = entry
        else:
            top[key] = entry
    return top, deep


def _snap_obs() -> dict:
    snap = {}
    for rel in GUARDED_OBS:
        p = OBS_EXTRAS / rel
        if p.is_file():
            st = p.stat()
            snap[rel] = {"size": st.st_size, "mtime": st.st_mtime_ns,
                         "content": p.read_bytes()}
    return snap


def _check_file(p, rel: str, problems: list, stat_result=None):
    """Compare ONE file against the session snapshot (r25 G5 semantics):
    * known small file (<= 64 KiB) changed  -> violation + RESTORE bytes;
    * known large file, mtime changed       -> violation + RESTORE mtime;
    * known large file, size changed        -> violation once + RE-BASE;
    * NEW non-allowlist file (ADDED)        -> violation once + RE-BASE
      (accepted as the new baseline -- one red test, no cascade).
    Allowlist changes are silent (the launchers' contract writes)."""
    meta = _SNAP.get(rel)
    allowlisted = _is_allowlisted(rel)
    st = stat_result if stat_result is not None else p.stat()
    path = pathlib.Path(p.path) if hasattr(p, "path") else pathlib.Path(p)
    if meta is None:
        if not allowlisted:
            problems.append(f"live/{rel} (ADDED)")
            _SNAP[rel] = {"size": st.st_size, "mtime": st.st_mtime_ns,
                          "content": None}
            _REBASED.add(rel)   # r25 G5: no cascade, not part of the original
        return
    if meta.get("dir"):
        return
    if st.st_size != meta["size"]:
        if not allowlisted:
            problems.append(f"live/{rel} (MODIFIED size)")
        # r25 G5: restore small content; for large files re-base (no cascade)
        if meta["content"] is not None:
            path.write_bytes(meta["content"])
            os.utime(path, ns=(meta["mtime"], meta["mtime"]))
        else:
            meta["size"] = st.st_size
            meta["mtime"] = st.st_mtime_ns
        return
    if st.st_mtime_ns != meta["mtime"]:
        if not allowlisted:
            problems.append(f"live/{rel} (MODIFIED mtime)")
        # restore the mtime (large files keep their bytes; small ones too)
        os.utime(path, ns=(meta["mtime"], meta["mtime"]))


def _scan_live() -> list:
    """r25 G6: cheap per-test scan -- top level of live/ + obs-relay/ +
    crash-* fully; lmcache-build/ top-level entries only. Uses os.scandir
    (stat comes with the dirent -- no per-file syscall through pathlib).
    Returns violation strings (empty list = clean)."""
    if not REPO_LIVE.is_dir():
        return []
    problems = []
    with os.scandir(REPO_LIVE) as it:
        entries = sorted(it, key=lambda e: e.name)
    for e in entries:
        rel = e.name
        if e.is_dir(follow_symlinks=False):
            if rel == "lmcache-build":
                with os.scandir(e.path) as sub:
                    for c in sorted(sub, key=lambda x: x.name):
                        _check_file(c, f"{rel}/{c.name}", problems,
                                    stat_result=c.stat(follow_symlinks=False))
            elif rel.startswith(WALK_PREFIXES):
                for c in sorted(pathlib.Path(e.path).rglob("*")):
                    if c.is_file():
                        _check_file(c, str(c.relative_to(REPO_LIVE)),
                                    problems)
            else:
                _check_file(e, rel, problems,
                            stat_result=e.stat(follow_symlinks=False))
        else:
            _check_file(e, rel, problems,
                        stat_result=e.stat(follow_symlinks=False))
    return problems


def _restore_remaining():
    """Restore everything the cheap scan did not cover (allowlist records,
    top-level entries only known from the full session snapshot). r25 G6:
    deep entries under lmcache-build/** are NOT in _SNAP -- they are only
    checked by the full walk at session end."""
    if not REPO_LIVE.is_dir():
        return
    for rel, meta in _SNAP.items():
        if meta.get("dir"):
            (REPO_LIVE / rel).mkdir(parents=True, exist_ok=True)
            continue
        p = REPO_LIVE / rel
        if not p.exists():
            if meta["content"] is not None:
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_bytes(meta["content"])
            continue
        st = p.stat()
        if st.st_size != meta["size"] or st.st_mtime_ns != meta["mtime"]:
            if meta["content"] is not None:
                p.write_bytes(meta["content"])
                os.utime(p, ns=(meta["mtime"], meta["mtime"]))


@pytest.hookimpl(tryfirst=True, hookwrapper=True)
def pytest_runtest_makereport(item, call):
    """r25 G5: a tree-guard violation must fail EXACTLY the test that caused
    it as a FAILED test (the fixture raises in teardown -> pytest would
    report an ERROR; the acceptance counts 'N passed, 1 failed'). The
    fixture marks the item; this hook downgrades the teardown error."""
    outcome = yield
    report = outcome.get_result()
    if report.when == "teardown" and report.outcome == "error":
        if getattr(item, "_kvp_tree_violation", False):
            report.outcome = "failed"


@pytest.fixture(scope="session", autouse=True)
def _kvp_live_isolation(request):
    """Point KVP_LIVE_DIR (and KVP_OBS_DIR for the extras render) at temp
    dirs for the whole session and snapshot the repo tree (E1 + G5/G6)."""
    global _SNAP, _SNAP_DEEP, _OBS_SNAP, _SNAP_ORIG
    _SNAP, _SNAP_DEEP = _snap_live()
    _SNAP_ORIG = dict(_SNAP)
    _OBS_SNAP = _snap_obs()
    tmp_live = pathlib.Path(tempfile.mkdtemp(prefix="kvp-test-live-"))
    os.environ["KVP_LIVE_DIR"] = str(tmp_live)
    os.environ["LIVE_DIR"] = str(tmp_live)
    # r24 E1.3: extras-up.sh renders generated files -- point OBS_DIR at a tmp
    # COPY of the extras sources so those never appear in the repo tree.
    tmp_obs = pathlib.Path(tempfile.mkdtemp(prefix="kvp-test-obs-"))
    if OBS_EXTRAS.is_dir():
        shutil.copytree(OBS_EXTRAS, tmp_obs / "extras")
    os.environ["KVP_OBS_DIR"] = str(tmp_obs)
    yield
    os.environ.pop("KVP_LIVE_DIR", None)
    os.environ.pop("LIVE_DIR", None)
    os.environ.pop("KVP_OBS_DIR", None)
    shutil.rmtree(tmp_live, ignore_errors=True)
    shutil.rmtree(tmp_obs, ignore_errors=True)
    # session GUARD (full walk, once per session -- includes the deep entries)
    after_top, after_deep = _snap_live()
    problems = []
    for rel in after_top:
        if rel not in _SNAP:
            key = rel[:-1] if rel.endswith("/") else rel
            if not _is_allowlisted(key):
                problems.append(f"ADDED {rel}")
    for rel in _SNAP:
        if rel not in after_top:
            problems.append(f"REMOVED {rel}")
    for rel in after_deep:
        if rel not in _SNAP_DEEP:
            problems.append(f"ADDED {rel}")
    for rel in _SNAP_DEEP:
        if rel not in after_deep:
            problems.append(f"REMOVED {rel}")
    obs_after = _snap_obs()
    for rel in obs_after:
        if rel not in _OBS_SNAP:
            problems.append(f"OBS-ADDED {rel}")
    if problems:
        pytest.fail(
            "r25 E1/G5 GUARD: the repo tree was modified by the test run "
            "(tests must use the isolated KVP_LIVE_DIR / tmp dirs): "
            + ", ".join(problems[:20]))


